using System.Text;
using System.Text.RegularExpressions;

namespace Loudify.Core;

/// <summary>
/// Builds the Equalizer APO configuration text. Loudify owns loudify.txt and
/// only adds an Include line to the user's config.txt.
/// </summary>
public static partial class EqualizerApoConfig
{
    public const string ConfigFileName = "config.txt";
    public const string LoudifyFileName = "loudify.txt";
    public const string BackupFileName = "config.txt.loudify-backup";
    public const string IncludeLine = "Include: " + LoudifyFileName;

    // config.txt as shipped by the Equalizer APO installer. It lowers the volume
    // by 6 dB, which would defeat the purpose, so it is replaced instead of extended.
    private static readonly string[] DefaultConfigLines =
    {
        "Preamp: -6 dB",
        "Include: example.txt",
        "GraphicEQ: 25 0; 40 0; 63 0; 100 0; 160 0; 250 0; 400 0; 630 0; 1000 0; 1600 0; 2500 0; 4000 0; 6300 0; 10000 0; 16000 0",
    };

    public static string BuildLoudifyConfig(LoudifySettings settings, string limiterPath)
    {
        settings = settings.Sanitized();
        var sb = new StringBuilder();
        sb.Append("# Generated by Loudify. Manual changes will be overwritten.\r\n");
        if (!settings.Enabled)
        {
            sb.Append("# Boost disabled.\r\n");
            return sb.ToString();
        }

        // Only process playback (post-mix); never touch microphones that also have
        // Equalizer APO installed.
        sb.Append("Stage: post-mix\r\n");

        // Loud mode EQ goes before the limiter, which then keeps the result under the ceiling.
        double loud = LoudMode.Amount(settings.GainDb);
        if (loud > 0)
        {
            sb.Append("# Loud mode ").Append(LimiterParameters.Format(Math.Round(loud * 100))).Append("%\r\n");
            sb.Append("Filter: ON LS Fc ").Append(LimiterParameters.Format(LoudMode.LowShelfHz))
                .Append(" Hz Gain ").Append(LimiterParameters.Format(Math.Round(LoudMode.LowShelfGainDb * loud, 2))).Append(" dB\r\n");
            sb.Append("Filter: ON PK Fc ").Append(LimiterParameters.Format(LoudMode.PresenceHz))
                .Append(" Hz Gain ").Append(LimiterParameters.Format(Math.Round(LoudMode.PresenceGainDb * loud, 2)))
                .Append(" dB Q ").Append(LimiterParameters.Format(LoudMode.PresenceQ)).Append("\r\n");
        }

        double ceiling = LoudMode.EffectiveCeilingDb(settings.CeilingDb, loud);
        sb.Append("VSTPlugin: Library \"").Append(limiterPath).Append('"')
            .Append(" Gain ").Append(LimiterParameters.Format(LimiterParameters.GainToNormalized(settings.GainDb)))
            .Append(" Ceiling ").Append(LimiterParameters.Format(LimiterParameters.CeilingToNormalized(ceiling)))
            .Append(" Release ").Append(LimiterParameters.Format(LimiterParameters.ReleaseToNormalized(settings.ReleaseMs)))
            .Append("\r\n");
        return sb.ToString();
    }

    public static bool IsDefaultConfig(string configText)
    {
        var lines = SplitLines(configText).Where(l => l.Length > 0).ToArray();
        return lines.SequenceEqual(DefaultConfigLines);
    }

    public static bool ContainsInclude(string configText) =>
        SplitLines(configText).Any(l => IncludeRegex().IsMatch(l));

    /// <summary>
    /// Returns config.txt content that includes loudify.txt, or null when the
    /// existing content already does.
    /// </summary>
    public static string? WithInclude(string? configText)
    {
        if (string.IsNullOrWhiteSpace(configText) || IsDefaultConfig(configText))
            return "# Loudify: the previous configuration was saved to " + BackupFileName + "\r\n" + IncludeLine + "\r\n";
        if (ContainsInclude(configText))
            return null;

        string separator = configText.EndsWith('\n') ? "" : "\r\n";
        return configText + separator + IncludeLine + "\r\n";
    }

    private static IEnumerable<string> SplitLines(string text) =>
        text.Split('\n').Select(l => l.Trim().TrimStart('﻿'));

    [GeneratedRegex(@"^Include:\s*loudify\.txt$", RegexOptions.IgnoreCase)]
    private static partial Regex IncludeRegex();
}
